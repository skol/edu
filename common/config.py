"""Единая конфигурация для всех рекомендательных моделей VK-LSVD.

Общие настройки одинаково называются и одинаково работают во всех моделях
(most_popular, fpmc, sasrec, light_gcn). Модель-специфичные параметры
объявляются в подклассах.
"""

from dataclasses import dataclass


@dataclass
class CommonConfig:
    # Путь к подвыборке датасета VK-LSVD.
    data_dir: str = "data/raw/VK-LSVD/subsamples/up0.001_ip0.001"

    # Тренировочный период: недели [start_week, end_week] включительно.
    # end_week не может превышать 24: неделя 25 существует только в папке
    # validation/ и используется исключительно как валидационная/тестовая.
    start_week: int = 0
    end_week: int = 24

    # Количество эпох обучения (у most_popular нет обучения — не используется).
    epochs: int = 10

    # Learning rate (у most_popular не используется).
    lr: float = 1e-3

    # Глубина топ-k для метрик и рекомендаций.
    k: int = 10

    # Минимальный размер позитивной истории, чтобы пользователь попал в
    # обучающую выборку. Применяется только там, где это уже было заложено
    # (fpmc), чтобы не менять качество моделей.
    min_history: int = 2

    # Максимальный размер истории: сверх этого значения отбрасываются старые
    # данные в текущем сэмпле. Применяется только в sasrec (эквивалент старого
    # max_len, без изменения поведения); для остальных моделей не используется.
    max_history: int = 32

    # Порог времени просмотра ролика (секунд), чтобы действие считалось
    # позитивным (>=). Действия короче считаются пропуском/свайпом.
    min_timespent_pos: int = 5

    # Seed воспроизводимости.
    seed: int = 42

    @property
    def val_week(self) -> int:
        """Валидационная неделя всегда идёт сразу за тренировочной частью.

        Если end_week < 24 — следующая неделя берётся из папки train/;
        если end_week == 24 — валидацией служит неделя 25 из папки validation/,
        которая никогда не используется для обучения.
        """
        assert self.end_week <= 24, (
            "Неделя 25 доступна только для валидации/теста, "
            "end_week не может быть больше 24"
        )
        assert self.start_week <= self.end_week, "start_week не может быть больше end_week"
        return self.end_week + 1

    @property
    def train_weeks(self) -> range:
        """Недели, используемые для обучения (неделя 25 сюда не попадает)."""
        return range(self.start_week, self.end_week + 1)